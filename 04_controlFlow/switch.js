const month = "march";
switch (month) {
  case "jan":
    console.log("January");
    break;

  case "feb":
    console.log("Febuary");
    break;
  case "mar":
    console.log("March");
    break;
  case "apr":
    console.log("April");
    break;
  case "may":
    console.log("May");
    break;
  case "june":
    console.log("June");
    break;
   default:
     console.log("default case ");
     break;
}
